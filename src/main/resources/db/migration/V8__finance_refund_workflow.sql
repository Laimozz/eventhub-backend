CREATE TABLE payment_finances (
    payments_id INTEGER PRIMARY KEY REFERENCES payments(id),
    gross_amount NUMERIC(19,2) NOT NULL CHECK (gross_amount >= 0),
    platform_fee NUMERIC(19,2) NOT NULL CHECK (platform_fee >= 0),
    organizer_amount NUMERIC(19,2) NOT NULL CHECK (organizer_amount >= 0),
    credited BOOLEAN NOT NULL DEFAULT FALSE,
    settled BOOLEAN NOT NULL DEFAULT FALSE,
    reversed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CHECK (gross_amount = platform_fee + organizer_amount),
    CHECK (NOT settled OR credited)
);

