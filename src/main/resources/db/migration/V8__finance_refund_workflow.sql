CREATE TABLE refund_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refunds_id INTEGER NOT NULL REFERENCES refunds(id),
    request_id VARCHAR(32) NOT NULL UNIQUE,
    command VARCHAR(20) NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    response_code VARCHAR(2),
    transaction_status VARCHAR(2),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE TABLE refund_bank_accounts (
    payment_id INTEGER PRIMARY KEY REFERENCES payments(id),
    bank_code VARCHAR(50) NOT NULL,
    account_number VARCHAR(50) NOT NULL,
    account_holder_name VARCHAR(255) NOT NULL,
    verified_by INTEGER NOT NULL REFERENCES users(id),
    verified_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE refund_evidence (
    refunds_id INTEGER PRIMARY KEY REFERENCES refunds(id),
    transaction_code VARCHAR(255) NOT NULL UNIQUE,
    content_type VARCHAR(50) NOT NULL,
    content BYTEA NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 5242880),
    recorded_by INTEGER NOT NULL REFERENCES users(id),
    recorded_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE INDEX idx_refunds_workflow ON refunds(status, id);
CREATE INDEX idx_refund_attempts_refund ON refund_attempts(refunds_id, id);
